import java.util.*;
public class Interger1 {
    public static void main (String[] args) {
        int[] arr = {1,2,3,4};
        int count = 0;
        for (int i = 0; i < arr.length; i++) {
            count++;
        }
        System.out.println("Number of elements in the array: " + count);
    }
    
}
